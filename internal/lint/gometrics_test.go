const sampleGo = `package sample

import (
	"fmt"
	"os"
	"strings"
)

type T[K any] struct{}

func (t *T[K]) Method(a, b int, c string) {
	fmt.Println(a, b, c)
}

func Long(x int) int {
	x++
	x++
	x++
	return x
}

func Wide(a, b, c, d int, e string, _ bool) {}

func use() { _ = os.Args; _ = strings.Join }
`

func TestMeasureGo(t *testing.T) {
	m, err := MeasureGo("sample.go", []byte(sampleGo))
	if err != nil {
		t.Fatal(err)
	}
	if m.Package != "sample" || m.Lines != 24 || m.Test || m.Generated || len(m.Imports) != 3 {
		t.Fatalf("file metrics = %+v", m)
	}
	want := []FuncMetrics{
		{Name: "T.Method", Line: 11, Lines: 3, Params: 3},
		{Name: "Long", Line: 15, Lines: 6, Params: 1},
		{Name: "Wide", Line: 22, Lines: 1, Params: 6},
		{Name: "use", Line: 24, Lines: 1, Params: 0},
	}
	if len(m.Funcs) != len(want) {
		t.Fatalf("funcs = %+v", m.Funcs)
	}
	for i, w := range want {
		if m.Funcs[i] != w {
			t.Errorf("func %d = %+v, want %+v", i, m.Funcs[i], w)
		}
	}
}

func TestGoQualityRule(t *testing.T) {
	rule := NewGoQualityRule(GoLimits{FileLines: 20, TestFileLines: 100, FuncLines: 5, Params: 5, Imports: 2})
	findings := NewLinter(rule).LintBytes("sample.go", []byte(sampleGo), LangAuto)
	got := map[string]int{}
	for _, f := range findings {
		if f.Severity != SeverityWarning {
			t.Errorf("Go quality findings must be warnings: %+v", f)
		}
		got[fmt.Sprintf("%s@%d", f.RuleID, f.Line)]++
	}
	for _, key := range []string{"go-file-length@1", "go-import-fanout@1", "go-func-length@15", "go-params@22"} {
		if got[key] != 1 {
			t.Errorf("missing %s in %v", key, got)
		}
	}
	if len(findings) != 4 {
		t.Errorf("want exactly 4 findings, got %+v", findings)
	}

	// The same source as a test file uses the test-file limit.
	findings = NewLinter(rule).LintBytes("sample_test.go", []byte(sampleGo), LangAuto)
	for _, f := range findings {
		if f.RuleID == "go-file-length" {
			t.Errorf("test file under test_file_lines must not warn: %+v", f)
		}
	}

	generated := "// Code generated by x. DO NOT EDIT.\n\n" + sampleGo
	if findings := NewLinter(rule).LintBytes("gen.go", []byte(generated), LangAuto); len(findings) != 0 {
		t.Errorf("generated files must be skipped, got %+v", findings)
	}

	if findings := NewLinter(rule).LintBytes("bad.go", []byte("package x\nfunc {"), LangAuto); len(findings) != 1 || findings[0].RuleID != "go-parse" {
		t.Errorf("unparsable Go must report go-parse, got %+v", findings)
	}
}

func TestEmbeddedLintSpec(t *testing.T) {
	spec, err := LoadSpec()
	if err != nil {
		t.Fatal(err)
	}
	if spec.Go.TestFileLines < spec.Go.FileLines {
		t.Errorf("test_file_lines (%d) should not be below file_lines (%d)", spec.Go.TestFileLines, spec.Go.FileLines)
	}

	// Every schema-required key must be a yaml tag the loader decodes.
	data, err := fs.ReadFile(harnez.DefaultFS, "spec/schemas/lint.schema.json")
	if err != nil {
		t.Fatal(err)
	}
	var schema struct {
		Properties map[string]struct {
			Required []string `json:"required"`
		} `json:"properties"`
	}
	if err := json.Unmarshal(data, &schema); err != nil {
		t.Fatal(err)
	}
	for _, key := range append(schema.Properties["go"].Required, schema.Properties["hotspots"].Required...) {
		if _, err := ParseSpec([]byte(strings.ReplaceAll(mustSpec(t), key+":", "x_"+key+":"))); err == nil {
			t.Errorf("renaming required key %q must fail strict decoding", key)
		}
	}

	for _, bad := range []string{"go: {file_lines: 0}", "unknown: 1"} {
		if _, err := ParseSpec([]byte(bad)); err == nil {
			t.Errorf("ParseSpec(%q) must fail", bad)
		}
	}
}

func mustSpec(t *testing.T) string {
	t.Helper()
	data, err := fs.ReadFile(harnez.DefaultFS, specPath)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}
